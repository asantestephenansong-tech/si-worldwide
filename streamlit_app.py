def clean(t):
 try: return "".join(c for c in unicodedata.normalize("NFKD", t) if not unicodedata.combining(c))
 except: return t
def get_key():
 try: return str(st.secrets.get("GROQ_API_KEY","")).strip().replace('"','').replace("'","")
 except: return ""
def ask(q, history):
 k=get_key()
 if not k.startswith("gsk_"): return "Add GROQ_API_KEY in Secrets!"
 msgs=[{"role":"system","content":"You are Stephen's Intelligence (SI). Premium AI by Stephen. Short elegant answers 2-4 sentences. No HTML tags. Remember conversation."}]
 for r,m in history[-6:]:
  if r in ["u","a"]: msgs.append({"role":"user" if r=="u" else "assistant","content":m})
 msgs.append({"role":"user","content":clean(q)})
 try:
  r=requests.post("https://api.groq.com/openai/v1/chat/completions",
   headers={"Authorization":f"Bearer {k}","Content-Type":"application/json"},
   json={"model":"openai/gpt-oss-20b","messages":msgs,"max_tokens":400},timeout=30)
  j=r.json()
  return j["choices"][0]["message"]["content"] if r.status_code==200 else "Error, try again"
 except Exception as e: return f"Error: {e}"

def make_image(prompt):
 safe=urllib.parse.quote_plus(clean(prompt)+" ultra detailed, 8k, cinematic lighting")
 return f"https://image.pollinations.ai/prompt/{safe}?width=1024&height=1024&nologo=true&seed={random.randint(1,9999999)}&model=flux"

if "ch" not in st.session_state: st.session_state.ch=[]

# DISPLAY CHAT
for r,m in st.session_state.ch:
 if r=="u": st.chat_message("user").write(m)
 elif r=="a": st.chat_message("assistant").write(m)
 else: st.chat_message("assistant").image(m, caption="Generated by SI 🎨")

# INPUT
q=st.chat_input("Ask anything or say 'draw...' for images...")

if q:
 ql=q.lower()
 is_image = any(w in ql for w in ["draw","image","picture","photo","generate","create","logo","paint"])

 st.session_state.ch.append(("u",q))

 if is_image:
  # give text + image
  a=ask(f"Describe briefly what {q} would look like in 1 sentence.", st.session_state.ch)
  st.session_state.ch.append(("a",a))
  st.session_state.ch.append(("i",make_image(q)))
 else:
  a=ask(q, st.session_state.ch)
  st.session_state.ch.append(("a",a))
 st.rerun()

