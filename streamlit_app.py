# --- FUNCTIONS ---
def clean(t):
 try: return "".join(c for c in unicodedata.normalize("NFKD", t) if not unicodedata.combining(c))
 except: return t

def get_key():
 try: return str(st.secrets.get("GROQ_API_KEY","")).strip().replace('"','').replace("'","")
 except: return ""

def ask(q, history):
 k=get_key()
 if not k.startswith("gsk_"): return "⚠️ Add GROQ_API_KEY in Streamlit Secrets!"
 msgs=[{"role":"system","content":"You are Stephen's Intelligence (SI), luxury AI by Stephen. Give short clear answers in 2-4 sentences. No HTML tags like <sup>. Remember conversation context. Be confident, elegant, helpful."}]
 for r,m in history[-6:]:
  if r in ["u","a"]: msgs.append({"role":"user" if r=="u" else "assistant","content":m})
 msgs.append({"role":"user","content":clean(q)})
 try:
  r=requests.post("https://api.groq.com/openai/v1/chat/completions",
   headers={"Authorization":f"Bearer {k}","Content-Type":"application/json"},
   json={"model":"openai/gpt-oss-20b","messages":msgs,"max_tokens":500,"temperature":0.7},timeout=40)
  j=r.json()
  if r.status_code==200: return j["choices"][0]["message"]["content"]
  return f"AI Error: {j}"
 except Exception as e: return f"Error: {e}"

def make_image(prompt):
 p = clean(prompt).strip()
 # Remove trigger words for better image
 for w in ["image of","picture of","photo of","draw an image of","draw a","draw","generate an image of","generate image of","create an image of","create image of","create a","create","show me","make a pic of","make a picture of"]:
  if p.lower().startswith(w):
   p = p[len(w):].strip()
 if not p: p = "beautiful landscape"
 quality = "ultra detailed, 8k, cinematic, highly detailed, sharp focus, professional, vibrant colors"
 safe=urllib.parse.quote_plus(f"{p}, {quality}")
 return f"https://image.pollinations.ai/prompt/{safe}?width=1024&height=1024&nologo=true&seed={random.randint(1,9999999)}&model=flux&enhance=true"

